import test from 'node:test';
import assert from 'node:assert/strict';
import {createRemotePresence, presenceAppearance, presenceLanguageLabel, visibleSocialActors} from '../js/adventure_presence_core.js';

test('remote movement faces each target until arrival, then uses the final network facing', () => {
    for (const [x,y,facing] of [[100,0,2],[-100,0,1],[0,100,0],[0,-100,3],[80,-100,3],[0.5,0,2]]) {
        const remote=createRemotePresence();remote.reset('room','self');
        remote.receive({type:'entered',roomId:'room'},0);
        remote.receive({type:'joined',id:'peer',x:0,y:0,facing:0},0);
        remote.receive({type:'relay',players:[{id:'peer',x,y,facing:(facing+1)%4}]},1000);
        const actor=remote.actors('room',1500)[0];
        assert.equal(actor.facing,facing);assert.equal(actor.moving,true);
        assert.equal(remote.actors('room',2000)[0].facing,(facing+1)%4);
        assert.equal(remote.actors('room',2000)[0].moving,false);
    }
});

test('a new target mid-movement turns from the interpolated position', () => {
    const remote=createRemotePresence();remote.reset('room','self');remote.receive({type:'entered'},0);
    remote.receive({type:'joined',id:'peer',x:0,y:0},0);
    remote.receive({type:'relay',players:[{id:'peer',x:100,y:0,facing:0}]},1000);
    remote.receive({type:'relay',players:[{id:'peer',x:50,y:-100,facing:2}]},1500);
    assert.deepEqual(remote.actors('room',1500)[0].position,{x:50,y:0});
    assert.equal(remote.actors('room',1750)[0].facing,3);
    assert.equal(remote.actors('room',2500)[0].facing,2);
});

test('primary language comes from role settings and survives a network appearance roundtrip', () => {
    for(const native of ['zh-CN','en','ja','ko']) {
        const data=presenceAppearance({languageLearning:{native},token:'secret'});
        assert.equal(presenceAppearance(data).native,native);
        assert.notEqual(presenceLanguageLabel(native),presenceLanguageLabel(undefined));
        assert.equal(data.token,undefined);
    }
    assert.equal(presenceAppearance({}).native,undefined);
});

test('crowded rooms hide generated bystanders but preserve accepted teammates and restore on departure', () => {
    const actors=[{profile:{id:'ai',kind:'companion'}},{profile:{id:'team',kind:'companion'}},{profile:{id:'account',kind:'account'}}];
    assert.equal(visibleSocialActors(actors,7).length,3);
    assert.deepEqual(visibleSocialActors(actors,8,['team']).map(a=>a.profile.id),['team','account']);
    assert.equal(visibleSocialActors(actors,0).length,3);
});


test('crowd count only includes located peers in the active room and clears on disconnect', () => {
    const remote=createRemotePresence();remote.reset('room','self');remote.receive({type:'entered'},0);
    remote.receive({type:'roster',players:[{id:'self',x:0,y:0},{id:'peer',x:1,y:1},{id:'pending'}]},0);
    assert.equal(remote.count('room'),1);assert.equal(remote.count('elsewhere'),0);
    remote.receive({type:'left',id:'peer'},1);assert.equal(remote.count('room'),0);
    remote.reset();assert.equal(remote.count('room'),0);
});


test('stationary heartbeat packets never prolong walking, including facing-only changes', () => {
    const remote=createRemotePresence();remote.reset('room','self');remote.receive({type:'entered'},0);
    remote.receive({type:'joined',id:'peer',x:0,y:0,facing:0},0);
    assert.equal(remote.actors('room',0)[0].moving,false);
    remote.receive({type:'relay',players:[{id:'peer',x:100,y:0,facing:2}]},1000);
    for (const at of [1200,1400,1600,1800,1950]) {
        remote.receive({type:'relay',players:[{id:'peer',x:100,y:0,facing:3}]},at);
    }
    const stopped=remote.actors('room',2000)[0];
    assert.deepEqual(stopped.position,{x:100,y:0});
    assert.equal(stopped.moving,false);assert.equal(stopped.facing,3);
    for (const at of [2100,2500,3000]) {
        remote.receive({type:'relay',players:[{id:'peer',x:100,y:0,facing:1}]},at);
        assert.equal(remote.actors('room',at)[0].moving,false);
    }
    remote.receive({type:'relay',players:[{id:'peer',x:200,y:0,facing:0}]},3100);
    assert.equal(remote.actors('room',3500)[0].moving,true);
    assert.equal(remote.actors('room',4100)[0].moving,false);
});
